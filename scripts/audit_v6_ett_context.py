"""Step 0 of the simulator-paired one-step ETT (AntMaze V6): is the expert
advice a_b of the SAME pre-intervention context as the queried action and its
outcome reconstructable, and is one-step motion deterministic?  No training.

The ETT of the PointMaze pipeline fits F(s, a_b, a_q) -> s' plus an onset
head on same-context tuples.  For AntMaze the behaviour policy is the
privileged teacher (`rockfall_clock_v6_teacher.LongTwoRockfallTeacher`): a
deterministic latched relay (leg / trail / stall-nudge state) whose only use
of the hidden context is the prospective go / wait decision taken the first
time it stands at a hazard mouth, from the zone's timetable.  So a_b at a
context (s, t, hidden) is a function of (i) the route INTENT (the collector's
detour coin, an independent RNG stream -- never the realised route), (ii)
the position history up to t (leg, trail, nudges, step), (iii) the timetable
and the step at which each zone's rule was consulted.

What this script does, in order:

  hidden   Per d05 episode: intent, U1 / U2, t0_1 / t0_2, rock jitter.  Read
           from the per-seed sidecars where they exist (seeds 606 / 610 /
           611); for seeds 607-609 (sidecars not on any node) REGENERATED by
           replaying the collector's fixed-order RNG consumption (an env
           seeded with the collection seed, one reset per episode in order;
           the route coin from `seed + ROUTE_SEED_OFFSET`), and VALIDATED
           exactly against the three available sidecars first.
  diag     Every logged row: a fresh teacher (intent) driven along the logged
           observations with the original timetable must reproduce the
           logged torque exactly and the recorded per-step holding zone;
           the teacher state before every anchor row is snapshotted.
  branch   Every pilot anchor: the branch's redrawn hidden context (the same
           hazard seed the generator used) -> the teacher state at t
           reconstructed from the logged history, the zone latches
           RE-DERIVED under the new timetable at the recorded consultation
           steps -> a_b; compared with the queried torque a_q (the logged
           one): diagonal / off-diagonal (hold vs drive), by region and
           time.  Under the ORIGINAL timetable the same reconstruction must
           give a_b == a_q (checked).
  step     One-step determinism as a HYPOTHESIS: (i) restore (s_t, original
           hidden, t), execute the logged torque, compare with the logged
           s_{t+1}, rows outside rock bursts vs inside; (ii) the existing
           branches' first post-query row vs the logged s_{t+1} (same torque,
           different hidden), all anchors, split by burst activity.
  report   Markdown.

Missing information is reported, not patched: the d05 log contains no
failures (every episode reached the goal), so onset labels exist only in the
simulator branches; and anything the reconstruction cannot establish stops
the label construction.

  python scripts/audit_v6_ett_context.py hidden|diag|branch|step|report
"""
