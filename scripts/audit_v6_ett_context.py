def snapshot(teacher):
  return {f: copy.deepcopy(getattr(teacher, f)) for f in TEACHER_FIELDS}


def restore_teacher(teacher, snap):
  for f, v in snap.items():
    setattr(teacher, f, copy.deepcopy(v))


def schedule_of(u, t0, t):
  return {'t': int(t), 'zones': {z: {'active': bool(u[z]), 'sampled_start': int(t0[z]), 'start': (int(t0[z]) if u[z] else None),
                                     'end': (int(t0[z]) + ROCKFALL_STEPS if u[z] else None)} for z in (1, 2)}}


def in_burst(u, t0, t):
  return {z: bool(u[z] and int(t0[z]) <= t < int(t0[z]) + ROCKFALL_STEPS) for z in (1, 2)}


def make_env_teacher(seed):
  import rockfall_clock_v6_teacher as CT
  from crl import envs as envs_mod
  cfg, teacher = CT.make_teacher(p_active_1=0.5, p_active_2=0.5)
  env = envs_mod.make_env(CT.ENV_NAME, cfg, seed=int(seed))
  return env, teacher


def obs58(env, row31):
  """The teacher's observation: the 29-dim state + the env's 29-dim goal template with the logged goal xy (as build_v6_branch_replay.restore sets it)."""
  full = np.array(env._goal_state_full, np.float32)
  full[:2] = row31[STATE_DIM:OBS_W]
  return np.concatenate([row31[:STATE_DIM].astype(np.float32), full])


