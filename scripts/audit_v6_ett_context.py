def replay_episode(env, teacher, obs, L, intent, u, t0, holding_ref=None, anchor_ts=()):
  """Drive a fresh teacher along the logged rows of one episode under the original timetable.  Returns per-row torques, the
  decision steps, and the teacher snapshots BEFORE acting at the requested anchor rows."""
  teacher.fresh(route=intent)
  A = np.zeros((L - 1, 8), np.float32); hold = np.full(L - 1, -1, np.int8); dstep = {1: -1, 2: -1}
  snaps = {}
  want = set(int(t) for t in anchor_ts)
  for t in range(L - 1):
    if t in want:
      snaps[t] = snapshot(teacher)
    before = dict(teacher._decision)
    A[t] = teacher.act(obs58(env, obs[t]), schedule_of(u, t0, t))
    for z in (1, 2):
      if before[z] is None and teacher._decision[z] is not None:
        dstep[z] = t
    hold[t] = -1 if teacher._holding_zone is None else int(teacher._holding_zone)
  return A, hold, dstep, snaps


