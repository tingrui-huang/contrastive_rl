def rederive_latches(snap, u_new, t0_new, dstep):
  """The zone latches under a NEW timetable: every zone whose rule the teacher had consulted (at the recorded step) is re-decided by the
  same rule at that step under the new schedule; unconsulted zones stay None (the rule fires when the mouth is reached)."""
  import rockfall_clock_v6_teacher as CT
  snap = copy.deepcopy(snap)
  for z in (1, 2):
    if snap['_decision'][z] is None:
      continue
    m = int(dstep[z]); assert m >= 0
    if not u_new[z]:
      normal = 'go'
    else:
      cross_end = m + CT.CROSSING_STEPS[z] + CT.SAFETY_MARGIN
      normal = 'wait' if CT.intervals_overlap(int(t0_new[z]), int(t0_new[z]) + ROCKFALL_STEPS, m, cross_end) else 'go'
    snap['_normal_decision'][z] = normal; snap['_decision'][z] = normal
    snap['_release_step'][z] = (int(t0_new[z]) + ROCKFALL_STEPS + CT.RELEASE_MARGIN) if normal == 'wait' else None
  return snap


